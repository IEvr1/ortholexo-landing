import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, basename, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import matter from "gray-matter";
import { marked } from "marked";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const articlesDir = join(root, "content", "articles");
const outDir = join(root, "src", "generated");
const outFile = join(outDir, "articles.ts");
const outJson = join(outDir, "articles.json");
const sitemapFile = join(root, "public", "sitemap.xml");

const SITE_URL = (process.env.VITE_SITE_URL ?? "https://ortholexo.gr").replace(
  /\/$/,
  "",
);

function slugFromFilename(filename) {
  return basename(filename, ".md");
}

function parseArticles() {
  const files = readdirSync(articlesDir)
    .filter((f) => f.endsWith(".md"))
    .sort();

  return files.map((file) => {
    const raw = readFileSync(join(articlesDir, file), "utf8");
    const { data, content } = matter(raw);
    const slug = slugFromFilename(file);
    const title = String(data.title ?? slug);
    const description = String(data.description ?? "");
    const date = String(data.date ?? new Date().toISOString().slice(0, 10));
    const html = marked.parse(content.trim(), { async: false });
    const bundle = data.bundle ?? undefined;
    const tags = Array.isArray(data.tags) ? data.tags : undefined;

    return {
      slug,
      title,
      description,
      date,
      html: String(html),
      ...(bundle ? { bundle } : {}),
      ...(tags ? { tags } : {}),
    };
  });
}

function writeArticlesModule(articles) {
  mkdirSync(outDir, { recursive: true });

  const body = articles
    .map(
      (a) => `  {
    slug: ${JSON.stringify(a.slug)},
    title: ${JSON.stringify(a.title)},
    description: ${JSON.stringify(a.description)},
    date: ${JSON.stringify(a.date)},
    html: ${JSON.stringify(a.html)},${a.bundle ? `\n    bundle: ${JSON.stringify(a.bundle)},` : ""}${a.tags ? `\n    tags: ${JSON.stringify(a.tags)},` : ""}
  }`,
    )
    .join(",\n");

  const source = `/* Auto-generated by scripts/generate-articles.mjs — do not edit */
export type BundleQuizItem = {
  id: string;
  prompt: string;
  options: string[];
  answerIndex: number;
};

export type ArticleBundle = {
  type: "resource";
  grade: number;
  topic: string;
  topicLabel: string;
  wordCount: number;
  words: { id: string; word: string; hint?: string }[];
  exercises: string[];
  quiz: BundleQuizItem[];
  miniGame: {
    mode: "choice" | "sentence";
    questions: BundleQuizItem[];
  };
  worksheet: { title: string; subtitle?: string };
  premium: { cta: string; url: string; trialDays: number };
};

export type Article = {
  slug: string;
  title: string;
  description: string;
  date: string;
  html: string;
  bundle?: ArticleBundle;
  tags?: string[];
};

export const articles: Article[] = [
${body}
];

export function getArticle(slug: string): Article | undefined {
  return articles.find((a) => a.slug === slug);
}

export function listArticles(): Article[] {
  return [...articles].sort((a, b) => (a.date < b.date ? 1 : -1));
}
`;

  writeFileSync(outFile, source, "utf8");
  writeFileSync(outJson, JSON.stringify(articles, null, 2), "utf8");
}

function writeSitemap(articles) {
  const today = new Date().toISOString().slice(0, 10);
  const urls = [
    { loc: `${SITE_URL}/`, lastmod: today, changefreq: "weekly", priority: "1.0" },
    {
      loc: `${SITE_URL}/articles`,
      lastmod: today,
      changefreq: "weekly",
      priority: "0.8",
    },
    ...articles.map((a) => ({
      loc: `${SITE_URL}/articles/${a.slug}`,
      lastmod: a.date,
      changefreq: "monthly",
      priority: a.bundle ? "0.85" : "0.7",
    })),
  ];

  const xml = `<?xml version="1.0" encoding="UTF-8"?>
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls
  .map(
    (u) => `  <url>
    <loc>${u.loc}</loc>
    <lastmod>${u.lastmod}</lastmod>
    <changefreq>${u.changefreq}</changefreq>
    <priority>${u.priority}</priority>
  </url>`,
  )
  .join("\n")}
</urlset>
`;

  writeFileSync(sitemapFile, xml, "utf8");
}

const articles = parseArticles();
writeArticlesModule(articles);
writeSitemap(articles);
console.log(`Generated ${articles.length} article(s) → src/generated/articles.ts`);
